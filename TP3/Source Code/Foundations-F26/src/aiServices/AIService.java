package aiServices;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;

/******
 *
 * <p> Title: AIService Class. </p>
 *
 * <p> Description: Provides the shared service that will send AI requests and
 * receive AI responses for the TP3 features that use AI. The service behavior
 * will be added as TP3 continues. </p>
 *
 * @author Venus Ho
 * @author Alexander Murray
 * @author Alan Shimp
 * @author Caleb Beaven
 * @author Krithik Duraisamy
 *
 * @version 1.0 2026-11-14 Initial shared AI service structure
 *
 */

public class AIService {

	// Defines how long the application waits to connect to the AI service
	private static final Duration CONNECT_TIMEOUT = Duration.ofSeconds(15);

	// Defines how long the application waits for the AI service to respond
	private static final Duration REQUEST_TIMEOUT = Duration.ofSeconds(60);

	// Reuses one HTTP client for all AI features in the application
	private static final HttpClient HTTP_CLIENT = HttpClient.newBuilder()
			.connectTimeout(CONNECT_TIMEOUT)
			.build();

	/******
	 *
	 * <p> Method: sendRequest() </p>
	 *
	 * <p> Description: Builds and sends one request to an OpenAI-compatible AI
	 * service. The API key, service URL, model, and prompts are supplied by the
	 * calling feature so this class can be shared by all TP3 AI features. </p>
	 *
	 * @param apiKey specifies the API key used to authorize the request
	 * @param serviceUrl specifies the OpenAI-compatible chat completion URL
	 * @param model specifies the AI model that will process the request
	 * @param systemPrompt specifies the instructions that guide the AI response
	 * @param userPrompt specifies the lesson information or question sent to the AI
	 * @return the text generated by the AI service
	 * @throws IOException when the service cannot be reached or returns an error
	 * @throws InterruptedException when the request is interrupted while waiting
	 *
	 */

	public static String sendRequest(String apiKey, String serviceUrl, String model,
			String systemPrompt, String userPrompt) throws IOException, InterruptedException {

		// Rejects missing configuration before attempting an internet connection
		validateRequiredValue(apiKey, "AI API key");
		validateRequiredValue(serviceUrl, "AI service URL");
		validateRequiredValue(model, "AI model");
		validateRequiredValue(systemPrompt, "AI system prompt");
		validateRequiredValue(userPrompt, "AI user prompt");

		// Builds the JSON body expected by an OpenAI-compatible service
		String requestBody = buildRequestBody(model, systemPrompt, userPrompt);

		// Creates the authorized HTTP request
		HttpRequest request = HttpRequest.newBuilder()
				.uri(URI.create(serviceUrl))
				.timeout(REQUEST_TIMEOUT)
				.header("Content-Type", "application/json")
				.header("Authorization", "Bearer " + apiKey)
				.POST(HttpRequest.BodyPublishers.ofString(requestBody))
				.build();

		// Sends the request and receives the response as text
		HttpResponse<String> response = HTTP_CLIENT.send(
				request,
				HttpResponse.BodyHandlers.ofString());

		// Rejects unsuccessful service responses
		if (response.statusCode() < 200 || response.statusCode() >= 300) {
			throw new IOException("AI service returned status " + response.statusCode()
					+ ": " + truncate(response.body(), 300));
		}

		// Extracts only the generated message from the JSON response
		String generatedText = extractAssistantMessage(response.body()).trim();

		// Rejects successful responses that do not contain generated text
		if (generatedText.isEmpty()) {
			throw new IOException("AI service returned an empty response");
		}

		return generatedText;
	}

	/******
	 *
	 * <p> Method: buildRequestBody() </p>
	 *
	 * <p> Description: Creates the JSON request body containing the selected AI
	 * model, system instructions, and user prompt. </p>
	 *
	 * @param model specifies the AI model included in the request
	 * @param systemPrompt specifies the instructions for the AI
	 * @param userPrompt specifies the content submitted by the user
	 * @return the completed JSON request body
	 *
	 */

	private static String buildRequestBody(String model, String systemPrompt, String userPrompt) {
		return "{"
				+ "\"model\":\"" + escapeJson(model) + "\","
				+ "\"temperature\":0.4,"
				+ "\"max_tokens\":1024,"
				+ "\"messages\":["
				+ "{\"role\":\"system\",\"content\":\"" + escapeJson(systemPrompt) + "\"},"
				+ "{\"role\":\"user\",\"content\":\"" + escapeJson(userPrompt) + "\"}"
				+ "]"
				+ "}";
	}

	/******
	 *
	 * <p> Method: extractAssistantMessage() </p>
	 *
	 * <p> Description: Finds and decodes the first generated message in an
	 * OpenAI-compatible JSON response. </p>
	 *
	 * @param json specifies the complete JSON response returned by the AI service
	 * @return the decoded message text, or an empty string when no message exists
	 *
	 */

	private static String extractAssistantMessage(String json) {
		if (json == null) return "";

		int messageIndex = json.indexOf("\"message\"");
		int searchStart = messageIndex >= 0 ? messageIndex : 0;
		int contentIndex = json.indexOf("\"content\"", searchStart);
		if (contentIndex < 0) return "";

		int colonIndex = json.indexOf(':', contentIndex);
		if (colonIndex < 0) return "";

		int quoteIndex = json.indexOf('"', colonIndex + 1);
		if (quoteIndex < 0) return "";

		StringBuilder message = new StringBuilder();
		boolean escaped = false;

		for (int index = quoteIndex + 1; index < json.length(); index++) {
			char current = json.charAt(index);

			if (escaped) {
				switch (current) {

				// Converts the JSON newline marker into a newline character
				case 'n':
					message.append('\n');
					break;

				// Converts the JSON carriage return marker into a carriage return
				case 'r':
					message.append('\r');
					break;

				// Converts the JSON tab marker into a tab character
				case 't':
					message.append('\t');
					break;

				// Restores a quotation mark that was escaped inside the JSON text
				case '"':
					message.append('"');
					break;

				// Restores a backslash that was escaped inside the JSON text
				case '\\':
					message.append('\\');
					break;

				// Restores a forward slash that was escaped inside the JSON text
				case '/':
					message.append('/');
					break;

				// Converts the JSON backspace marker into a backspace character
				case 'b':
					message.append('\b');
					break;

				// Converts the JSON form feed marker into a form feed character
				case 'f':
					message.append('\f');
					break;

				// Decodes a Unicode escape sequence into its matching character
				case 'u':
					index = appendUnicodeCharacter(json, index, message);
					break;

				// Keeps an unknown escaped character instead of discarding it
				default:
					message.append(current);
				}
				escaped = false;
			} else if (current == '\\') {
				escaped = true;
			} else if (current == '"') {
				return message.toString();
			} else {
				message.append(current);
			}
		}

		return "";
	}

	/******
	 *
	 * <p> Method: appendUnicodeCharacter() </p>
	 *
	 * <p> Description: Decodes one Unicode escape sequence found in an AI JSON
	 * response and adds it to the generated message. </p>
	 *
	 * @param json specifies the JSON response containing the Unicode sequence
	 * @param escapeIndex specifies the position of the Unicode escape marker
	 * @param message specifies the generated message being assembled
	 * @return the last index used by the Unicode sequence
	 *
	 */

	private static int appendUnicodeCharacter(String json, int escapeIndex, StringBuilder message) {
		if (escapeIndex + 4 >= json.length()) {
			message.append('u');
			return escapeIndex;
		}

		try {
			int characterCode = Integer.parseInt(
					json.substring(escapeIndex + 1, escapeIndex + 5), 16);
			message.append((char) characterCode);
			return escapeIndex + 4;
		} catch (NumberFormatException exception) {
			message.append('u');
			return escapeIndex;
		}
	}

	/******
	 *
	 * <p> Method: escapeJson() </p>
	 *
	 * <p> Description: Escapes special characters before text is placed inside a
	 * JSON request. </p>
	 *
	 * @param text specifies the text being added to the JSON request
	 * @return the escaped text safe for use inside a JSON string
	 *
	 */

	private static String escapeJson(String text) {
		if (text == null) return "";

		StringBuilder escapedText = new StringBuilder(text.length() + 16);

		for (int index = 0; index < text.length(); index++) {
			char current = text.charAt(index);

			switch (current) {
			// Escapes quotation marks so they do not end the JSON string early
			case '"':
				escapedText.append("\\\"");
				break;

			// Escapes backslashes so they remain part of the submitted text
			case '\\':
				escapedText.append("\\\\");
				break;

			// Converts newline characters into the JSON newline marker
			case '\n':
				escapedText.append("\\n");
				break;

			// Converts carriage returns into the JSON carriage return marker
			case '\r':
				escapedText.append("\\r");
				break;

			// Converts tab characters into the JSON tab marker
			case '\t':
				escapedText.append("\\t");
				break;

			// Converts backspace characters into the JSON backspace marker
			case '\b':
				escapedText.append("\\b");
				break;

			// Converts form feed characters into the JSON form feed marker
			case '\f':
				escapedText.append("\\f");
				break;
                
			// Keeps normal text and safely encodes other control characters
			default:
				if (current < 0x20) {
					escapedText.append(String.format("\\u%04x", (int) current));
				} else {
					escapedText.append(current);
				}
			}
		}

		return escapedText.toString();
	}

	/******
	 *
	 * <p> Method: validateRequiredValue() </p>
	 *
	 * <p> Description: Verifies that a required AI request value is present before
	 * an HTTP request is created. </p>
	 *
	 * @param value specifies the required value being checked
	 * @param valueName specifies the readable name used by an error message
	 *
	 */

	private static void validateRequiredValue(String value, String valueName) {
		if (value == null || value.isBlank()) {
			throw new IllegalArgumentException(valueName + " is missing");
		}
	}

	/******
	 *
	 * <p> Method: truncate() </p>
	 *
	 * <p> Description: Shortens a service error response before it is included in
	 * an application error message. </p>
	 *
	 * @param text specifies the error response returned by the service
	 * @param maximumLength specifies the largest number of characters to keep
	 * @return the original text or its shortened form
	 *
	 */

	private static String truncate(String text, int maximumLength) {
		if (text == null) return "";
		return text.length() <= maximumLength
				? text
				: text.substring(0, maximumLength) + "...";
	}

}
